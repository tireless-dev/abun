    val passThroughAccent: Color = notesAccent,
    val passThroughSoft: Color = notesSoft,
    val statusClearedAccent: Color = textTertiary,
    val statusClearedSoft: Color = surfaceMuted,
    val statusDraftAccent: Color = warning,
    val statusDraftSoft: Color = notesSoft,
    val statusScheduledAccent: Color = primary,
    val statusScheduledSoft: Color = tasksSoft,
    val isDark: Boolean = false,
)

