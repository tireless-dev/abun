internal fun appColors(colorScheme: ColorScheme): AppColors {
    val isDark = colorScheme.background == DarkColorScheme.background
    return AppColors(
        background = colorScheme.background,
        surface = colorScheme.surface,
        surfaceElevated = colorScheme.surfaceContainer,
        surfaceMuted = colorScheme.surfaceContainerHigh,
        textPrimary = colorScheme.onSurface,
        textSecondary = colorScheme.onSurfaceVariant,
        textTertiary = if (isDark) Color(0xFF94A3B8) else Color(0xFF5B6B82),
        border = colorScheme.outlineVariant,
        borderStrong = colorScheme.outline,
        primary = colorScheme.primary,
        success = if (isDark) Color(0xFF4DB89E) else Color(0xFF0F766E),
        warning = if (isDark) Color(0xFFFBBF24) else Color(0xFFB45309),
        error = colorScheme.error,
        onSurfaceVariant = colorScheme.onSurfaceVariant,
        canvas = if (isDark) Color(0xFF111315) else Color(0xFFF7F7F4),
        cardBorder = if (isDark) Color(0xFF282C32) else Color(0xFFE2E8F0),
        hairline = if (isDark) Color(0xFF22252A) else Color(0xFFEFEFEA),
        pillSurface = if (isDark) Color(0xFF22262C) else Color(0xFF111315),
        subnavTrack = if (isDark) Color(0xFF1E2227) else Color(0xFFEAE9E3),
        tasksAccent = if (isDark) Color(0xFF7B8CE8) else Color(0xFF3B4CCA),
        tasksSoft = if (isDark) Color(0xFF1F2442) else Color(0xFFEEF0FF),
        financeAccent = if (isDark) Color(0xFF4DB89E) else Color(0xFF0F766E),
        financeSoft = if (isDark) Color(0xFF16332D) else Color(0xFFE8F5F1),
        notesAccent = if (isDark) Color(0xFFFBBF24) else Color(0xFFB45309),
        notesSoft = if (isDark) Color(0xFF382914) else Color(0xFFFEF3C7),
        thingsAccent = if (isDark) Color(0xFFC97A96) else Color(0xFF8F4762),
        thingsSoft = if (isDark) Color(0xFF361D27) else Color(0xFFF9EDF2),
        passThroughAccent = if (isDark) Color(0xFFFBBF24) else Color(0xFFB45309),
        passThroughSoft = if (isDark) Color(0xFF382914) else Color(0xFFFEF3C7),
        statusClearedAccent = if (isDark) Color(0xFF94A3B8) else Color(0xFF5B6B82),
        statusClearedSoft = if (isDark) Color(0xFF26292E) else Color(0xFFF2F1EB),
        statusDraftAccent = if (isDark) Color(0xFFFBBF24) else Color(0xFFB45309),
        statusDraftSoft = if (isDark) Color(0xFF382914) else Color(0xFFFEF3C7),
        statusScheduledAccent = if (isDark) Color(0xFF93C5FD) else Color(0xFF1D4ED8),
        statusScheduledSoft = if (isDark) Color(0xFF172554) else Color(0xFFEFF6FF),
        isDark = isDark,
    )
}
