import { execSync } from "node:child_process";
import { statSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const apiDir = resolve(__dirname, "..");
const rootDir = resolve(apiDir, "../..");

const pkg = JSON.parse(readFileSync(join(apiDir, "package.json"), "utf8")) as {
  name?: string;
  version?: string;
};

const baseVersion = pkg.version || "0.0.0";
const appName = pkg.name || "api";

let commitHash = "unknown";
let buildTimestamp = "";

try {
  const status = execSync("git status --porcelain", { cwd: rootDir, encoding: "utf8" }).trim();
  const dirtyLines = status
    ? status.split("\n").filter((line) => {
        const file = line.slice(3).trim();
        return file && !file.endsWith("src/version.ts");
      })
    : [];
  const isDirty = dirtyLines.length > 0;

  if (isDirty) {
    let maxMtime = 0;
    for (const line of dirtyLines) {
      const file = line.slice(3).trim();
      const fullPath = join(rootDir, file);
      if (existsSync(fullPath)) {
        try {
          const mtime = statSync(fullPath).mtimeMs;
          if (mtime > maxMtime) maxMtime = mtime;
        } catch {}
      }
    }
    if (!maxMtime) maxMtime = Date.now();
    const d = new Date(maxMtime);
    const pad = (n: number) => String(n).padStart(2, "0");
    buildTimestamp = `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}${pad(d.getHours())}${pad(d.getMinutes())}`;
    commitHash = "wip";
  } else {
    buildTimestamp = execSync("git log -1 --format=%cd --date=format:%Y%m%d%H%M", { cwd: rootDir, encoding: "utf8" }).trim();
    commitHash = execSync("git rev-parse --short HEAD", { cwd: rootDir, encoding: "utf8" }).trim();
  }
} catch {
  const d = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  buildTimestamp = `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}${pad(d.getHours())}${pad(d.getMinutes())}`;
  commitHash = "unknown";
}

const fileContent = `// Auto-generated by scripts/generate-version.ts - DO NOT EDIT MANUALLY
export const API_NAME = ${JSON.stringify(appName)};
export const API_VERSION = ${JSON.stringify(baseVersion)};
export const API_COMMIT = ${JSON.stringify(commitHash)};
export const API_BUILD_TIME = ${JSON.stringify(buildTimestamp)};
`;

const targetFile = join(apiDir, "src", "version.ts");
if (!existsSync(targetFile) || readFileSync(targetFile, "utf8") !== fileContent) {
  writeFileSync(targetFile, fileContent, "utf8");
}
console.log(`[generate-version] Generated version: ${baseVersion}, commit: ${commitHash}, buildTime: ${buildTimestamp} -> src/version.ts`);
